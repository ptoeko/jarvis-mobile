// Ответы демонстрационного режима. Это фиксированные тексты, а не ИИ:
// каждый ответ помечается источником 'demo' и подписью «Демо-ответ».

const HELP_WORDS = ['помощь', 'справка', 'help', '?'];
const STATUS_WORDS = ['статус', 'status'];

export const DEMO_HELP_TEXT = [
  'Сейчас работает демонстрационный режим: ИИ не подключён, ответы — заранее заданные тексты.',
  'Реестр: напишите заметку и нажмите «В реестр». Приложение заполнит поля по правилам — только тем, что явно написано: дата, оси, отметки, нормы, срок, а также поля с метками «Объект:», «Вид работ:», «Подрядчик:», «Статус:». Остальное — «Не указано». Каждую запись проверьте и подтвердите вручную.',
  'Несколько заметок в одном сообщении разделяйте пустой строкой.',
  'Экспорт: на экране «Реестр» кнопки «Экспорт в Excel» и «Экспорт CSV».',
  'Файлы: кнопка-скрепка рядом с полем ввода — фото, видео, Word, PDF, Excel. Файлы заметки прикладываются к записи реестра. Содержимое файлов без ИИ не анализируется.',
  'Копирование и «Поделиться»: значки у каждого сообщения. Поделиться можно в Telegram, WhatsApp, MAX или по почте — сообщением, записью реестра или файлом Excel.',
  'Резервная копия: Настройки → «Сохранить копию». Храните файл вне телефона.',
  'Дальше: кнопка микрофона в приложении — этап 3, подключение ИИ — этап 4. Голос уже можно вводить микрофоном клавиатуры.',
  'Команды: «помощь», «статус».',
].join('\n');

function normalize(text) {
  return text.trim().toLowerCase().replace(/[.!]+$/, '');
}

// statusSummary — короткая строка о состоянии приложения (передаётся снаружи,
// чтобы модуль оставался независимым от браузера).
export function demoReply(userText, statusSummary = '') {
  const command = normalize(userText);
  if (HELP_WORDS.includes(command)) {
    return { source: 'demo', text: DEMO_HELP_TEXT };
  }
  if (STATUS_WORDS.includes(command)) {
    return {
      source: 'demo',
      text: statusSummary
        ? `Состояние приложения:\n${statusSummary}\nПодробности — на экране «Статус».`
        : 'Подробное состояние приложения — на экране «Статус».',
    };
  }
  return {
    source: 'demo',
    text:
      'Сообщение сохранено на этом телефоне. ИИ не подключён, поэтому содержание сообщения не анализируется. ' +
      'Чтобы занести заметку в реестр, нажмите «В реестр» вместо «Отправить». Напишите «помощь», чтобы узнать, что уже работает.',
  };
}

// Ответ после разбора заметок в черновики.
export function draftsReply(count, filledBy = 'rules') {
  const word = count % 10 === 1 && count % 100 !== 11 ? 'черновик' : count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 12 || count % 100 > 14) ? 'черновика' : 'черновиков';
  return {
    source: 'demo',
    text: filledBy === 'ai'
      ? `Создано ${count} ${word} записей реестра — поля заполнил ИИ агент. Проверьте их на экране «Реестр» и подтвердите каждую запись. Без подтверждения в реестр ничего не попадает.`
      : `Создано ${count} ${word} записей реестра (разбор по правилам, не ИИ). Проверьте поля на экране «Реестр» и подтвердите каждую запись. Без подтверждения в реестр ничего не попадает.`,
  };
}
